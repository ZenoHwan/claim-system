CREATE TABLE information_request (
    id            UUID PRIMARY KEY,
    claim_id      UUID        NOT NULL REFERENCES claim (id),
    requested_by  UUID        NOT NULL REFERENCES app_user (id),
    question      TEXT        NOT NULL,
    status        VARCHAR(20) NOT NULL CHECK (status IN ('OPEN', 'ANSWERED')),
    response_text TEXT,
    requested_at  TIMESTAMPTZ NOT NULL,
    answered_at   TIMESTAMPTZ,
    CHECK ((status = 'ANSWERED') = (answered_at IS NOT NULL))
);

CREATE INDEX information_request_claim_idx ON information_request (claim_id, requested_at);

CREATE TABLE claim_document (
    id                     UUID PRIMARY KEY,
    claim_id               UUID         NOT NULL REFERENCES claim (id),
    information_request_id UUID REFERENCES information_request (id),
    uploaded_by            UUID         NOT NULL REFERENCES app_user (id),
    file_name              VARCHAR(255) NOT NULL,
    content_type           VARCHAR(50)  NOT NULL CHECK (content_type IN ('application/pdf', 'image/jpeg', 'image/png')),
    size_bytes             BIGINT       NOT NULL CHECK (size_bytes > 0),
    -- generated by the server; never derived from the uploaded file name
    storage_key            VARCHAR(100) NOT NULL UNIQUE,
    uploaded_at            TIMESTAMPTZ  NOT NULL
);

CREATE INDEX claim_document_claim_idx ON claim_document (claim_id, uploaded_at);
